    )
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.ledger_has_role(_user_id uuid, _role text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM public.ledger_user_roles WHERE user_id = _user_id AND role = _role)
$$;
CREATE OR REPLACE FUNCTION public.ledger_is_account_active(_user_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT NOT COALESCE((SELECT disabled FROM public.ledger_account_status WHERE user_id = _user_id), false)
$$;
REVOKE ALL ON FUNCTION public.ledger_has_role(uuid, text) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.ledger_is_account_active(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.ledger_has_role(uuid, text), public.ledger_is_account_active(uuid) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.initialize_ledger_user_account()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.ledger_profiles (id, display_name)
  VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'display_name', NEW.raw_user_meta_data->>'name', NEW.raw_user_meta_data->>'full_name'))
  ON CONFLICT (id) DO NOTHING;
  -- Role never comes from client-controlled signup metadata.
  INSERT INTO public.ledger_user_roles (user_id, role) VALUES (NEW.id, 'user') ON CONFLICT DO NOTHING;
  INSERT INTO public.ledger_account_status (user_id) VALUES (NEW.id) ON CONFLICT DO NOTHING;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.initialize_ledger_user_account() FROM PUBLIC, anon, authenticated;
