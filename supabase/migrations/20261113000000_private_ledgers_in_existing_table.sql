    'ALTER SEQUENCE %s RESTART WITH %s',
    id_sequence,
    GREATEST(
      COALESCE(highest_uid, 0) + 1,
      COALESCE((SELECT last_value + 1 FROM pg_sequences
                WHERE schemaname = 'public' AND sequencename = (
                  SELECT relname FROM pg_class WHERE oid = id_sequence
