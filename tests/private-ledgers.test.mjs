import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

const migration = await readFile(
  new URL(
    "../supabase/migrations/20261113000000_private_ledgers_in_existing_table.sql",
    import.meta.url,
  ),
  "utf8",
);
const owner = "11111111-1111-4111-8111-111111111111";
const other = "22222222-2222-4222-8222-222222222222";
const newcomer = "33333333-3333-4333-8333-333333333333";

async function fixture({ missingOwner = false, identity = false } = {}) {
  const db = new PGlite();
  await db.exec(`
    CREATE ROLE anon NOLOGIN;
    CREATE ROLE authenticated NOLOGIN;
    CREATE ROLE service_role NOLOGIN BYPASSRLS;
    CREATE SCHEMA auth;
    GRANT USAGE ON SCHEMA auth, public TO anon, authenticated, service_role;
    CREATE TABLE auth.users (id uuid PRIMARY KEY, email text, raw_user_meta_data jsonb DEFAULT '{}');
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
      SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
    $$;
    INSERT INTO auth.users VALUES ('${other}', 'other@example.com', '{}');
    ${missingOwner ? "" : `INSERT INTO auth.users VALUES ('${owner}', 'gopinathr.r@gmail.com', '{"name":"Gopi"}');`}
    CREATE TABLE public.p_dlyexp (uid bigint ${identity ? "GENERATED BY DEFAULT AS IDENTITY" : ""} PRIMARY KEY, exp_desc text, owner_id uuid);
    INSERT INTO public.p_dlyexp (uid, exp_desc, owner_id) VALUES (1, 'Original', NULL), (1609, 'Latest original', NULL), (10, 'Already private', '${other}');
    ALTER TABLE public.p_dlyexp ENABLE ROW LEVEL SECURITY;
    CREATE POLICY "Legacy public access" ON public.p_dlyexp FOR ALL TO PUBLIC USING (true) WITH CHECK (true);
    GRANT ALL ON public.p_dlyexp TO anon, authenticated;
    GRANT SELECT (uid, exp_desc) ON public.p_dlyexp TO anon;
    CREATE TABLE public.profiles (id uuid PRIMARY KEY, unrelated_data text);
    INSERT INTO public.profiles VALUES ('${owner}', 'Keep this profile');
    CREATE POLICY "Unrelated profile policy" ON public.profiles FOR SELECT USING (true);
    CREATE TABLE public.ledger_user_roles (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
      role text NOT NULL CHECK (role IN ('admin', 'user')), created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(user_id, role)
    );
    GRANT UPDATE (role) ON public.ledger_user_roles TO authenticated;
  `);
  return db;
}

async function asUser(db, id, fn, role = "authenticated") {
  await db.exec(`BEGIN; SET LOCAL ROLE ${role};`);
  try {
    await db.query("SELECT set_config('request.jwt.claim.sub', $1, true)", [id]);
    const result = await fn();
    await db.exec("COMMIT");
    return result;
  } catch (error) {
    await db.exec("ROLLBACK");
    throw error;
  }
}

// Keep one database per test group: no external database, network, or user data.
test("existing plain-ID ledger: preserve ownership, initialize IDs, enforce isolation and account privileges", async (t) => {
  const db = await fixture();
  t.after(() => db.close());
  await db.exec(migration);
  assert.deepEqual((await db.query("SELECT unrelated_data FROM public.profiles")).rows, [
    { unrelated_data: "Keep this profile" },
  ]);
  assert.equal(
    (await db.query("SELECT count(*)::int AS n FROM pg_policies WHERE tablename='profiles'"))
      .rows[0].n,
    1,
  );
  assert.deepEqual(
    (await db.query("SELECT uid, owner_id FROM public.p_dlyexp ORDER BY uid")).rows,
    [
      { uid: 1, owner_id: owner },
      { uid: 10, owner_id: other },
      { uid: 1609, owner_id: owner },
    ],
  );
  assert.equal(
    (
      await db.query(
        "SELECT is_identity FROM information_schema.columns WHERE table_schema='public' AND table_name='p_dlyexp' AND column_name='uid'",
      )
    ).rows[0].is_identity,
    "YES",
  );

  await t.test("owner administrator sees only own entries; next insert is 1610", async () => {
    await asUser(db, owner, async () => {
      assert.equal((await db.query("SELECT count(*)::int AS n FROM public.p_dlyexp")).rows[0].n, 2);
      assert.equal(
        (await db.query("SELECT public.ledger_has_role(auth.uid(), 'admin') AS admin")).rows[0]
          .admin,
        true,
      );
      assert.equal(
        (
          await db.query(
            "INSERT INTO public.p_dlyexp (exp_desc) VALUES ('New expense') RETURNING uid, owner_id",
          )
        ).rows[0].uid,
        1610,
      );
      assert.equal(
        (
          await db.query(
            `UPDATE public.p_dlyexp SET exp_desc='Cannot touch' WHERE owner_id='${other}' RETURNING uid`,
          )
        ).rows.length,
        0,
      );
    });
  });
  await t.test("second user reads, inserts, updates, and deletes only own expenses", async () => {
    await asUser(db, other, async () => {
      assert.equal((await db.query("SELECT uid FROM public.p_dlyexp")).rows.length, 1);
      const inserted = (
        await db.query(
          "INSERT INTO public.p_dlyexp (exp_desc) VALUES ('Personal') RETURNING uid, owner_id",
        )
      ).rows[0];
      assert.equal(inserted.owner_id, other);
      assert.equal(
        (
          await db.query(
            `UPDATE public.p_dlyexp SET exp_desc='Edited' WHERE uid=${inserted.uid} RETURNING uid`,
          )
        ).rows.length,
        1,
      );
      assert.equal(
        (await db.query(`DELETE FROM public.p_dlyexp WHERE uid=${inserted.uid} RETURNING uid`)).rows
          .length,
        1,
      );
      assert.equal(
        (await db.query("DELETE FROM public.p_dlyexp WHERE uid=1 RETURNING uid")).rows.length,
        0,
      );
    });
    await assert.rejects(
      asUser(db, other, () =>
        db.query(`INSERT INTO public.p_dlyexp (owner_id) VALUES ('${owner}')`),
      ),
      /row-level security/,
    );
    await assert.rejects(
      asUser(db, other, () =>
        db.query(`UPDATE public.p_dlyexp SET owner_id='${owner}' WHERE uid=10`),
      ),
      /row-level security/,
    );
  });
  await t.test("anonymous users cannot read even formerly granted columns", async () => {
    await assert.rejects(
      asUser(db, "", () => db.query("SELECT uid, exp_desc FROM public.p_dlyexp"), "anon"),
      /permission denied/,
    );
  });
  await t.test("users cannot promote themselves or clear disabled status", async () => {
    await assert.rejects(
      asUser(db, other, () => db.query("UPDATE public.ledger_user_roles SET role='admin'")),
      /permission denied/,
    );
    await assert.rejects(
      asUser(db, other, () => db.query("UPDATE public.ledger_account_status SET disabled=false")),
      /permission denied/,
    );
    await asUser(db, other, async () => {
      assert.equal(
        (await db.query("SELECT count(*)::int AS n FROM public.ledger_profiles")).rows[0].n,
        1,
      );
      assert.equal(
        (
          await db.query(
            "UPDATE public.ledger_profiles SET display_name='Renamed' WHERE id=auth.uid() RETURNING id",
          )
        ).rows.length,
        1,
      );
    });
  });
  await t.test("disabled accounts cannot read or insert expenses", async () => {
    await db.query("UPDATE public.ledger_account_status SET disabled=true WHERE user_id=$1", [
      other,
    ]);
    await asUser(db, other, async () => {
      assert.equal((await db.query("SELECT count(*)::int AS n FROM public.p_dlyexp")).rows[0].n, 0);
    });
    await assert.rejects(
      asUser(db, other, () =>
        db.query("INSERT INTO public.p_dlyexp (exp_desc) VALUES ('Blocked')"),
      ),
      /row-level security/,
    );
  });
  await t.test(
    "new signup ignores role metadata and starts with an empty private ledger",
    async () => {
      await db.query(
        'INSERT INTO auth.users (id, email, raw_user_meta_data) VALUES ($1, \'new@example.com\', \'{"role":"admin","name":"New"}\')',
        [newcomer],
      );
      await asUser(db, newcomer, async () => {
        assert.deepEqual((await db.query("SELECT role FROM public.ledger_user_roles")).rows, [
          { role: "user" },
        ]);
        assert.equal(
          (await db.query("SELECT count(*)::int AS n FROM public.p_dlyexp")).rows[0].n,
          0,
        );
        assert.equal(
          (
            await db.query(
              "INSERT INTO public.p_dlyexp (exp_desc) VALUES ('First expense') RETURNING owner_id",
            )
          ).rows[0].owner_id,
          newcomer,
        );
      });
    },
  );
  await t.test("rerun preserves owners, status, rows, and an ahead sequence", async () => {
    const before = (await db.query("SELECT uid, owner_id FROM public.p_dlyexp ORDER BY uid")).rows;
    await db.exec("SELECT setval(pg_get_serial_sequence('public.p_dlyexp', 'uid'), 10000, true)");
    await db.exec(migration);
    assert.deepEqual(
      (await db.query("SELECT uid, owner_id FROM public.p_dlyexp ORDER BY uid")).rows,
      before,
    );
    assert.equal(
      (
        await db.query("SELECT disabled FROM public.ledger_account_status WHERE user_id=$1", [
          other,
        ])
      ).rows[0].disabled,
      true,
    );
    await asUser(db, owner, async () => {
      assert.equal(
        (
          await db.query(
            "INSERT INTO public.p_dlyexp (exp_desc) VALUES ('Ahead sequence') RETURNING uid",
          )
        ).rows[0].uid,
        10001,
      );
    });
  });
});

test("missing owner account aborts without altering the existing table or entries", async (t) => {
  const db = await fixture({ missingOwner: true });
  t.after(() => db.close());
  await assert.rejects(db.exec(migration), /Create\/verify exactly one Auth user/);
  await db.exec("ROLLBACK");
  assert.equal((await db.query("SELECT count(*)::int AS n FROM public.p_dlyexp")).rows[0].n, 3);
  assert.equal(
    (
      await db.query(
        "SELECT is_identity FROM information_schema.columns WHERE table_schema='public' AND table_name='p_dlyexp' AND column_name='uid'",
      )
    ).rows[0].is_identity,
    "NO",
  );
  assert.equal(
    (await db.query("SELECT to_regclass('public.ledger_profiles') AS name")).rows[0].name,
    null,
  );
});

test("already-present identity is repaired without changing IDs", async (t) => {
  const db = await fixture({ identity: true });
  t.after(() => db.close());
  await db.exec(migration);
  await asUser(db, owner, async () => {
    assert.equal(
      (
        await db.query(
          "INSERT INTO public.p_dlyexp (exp_desc) VALUES ('Identity expense') RETURNING uid",
        )
      ).rows[0].uid,
      1610,
    );
  });
});
