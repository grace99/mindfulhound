-- Run only against an empty disposable PostgreSQL database:
-- psql "$TEST_DATABASE_URL" -v ON_ERROR_STOP=1 -f tests/sql/expense-identity.sql
BEGIN;
CREATE TABLE public.p_dlyexp (
  uid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exp_desc text
);
INSERT INTO public.p_dlyexp (uid, exp_desc) VALUES (1, 'Existing import'), (5000, 'Highest imported ID');

-- Reproduce the reported failure before applying the repair.
DO $$
BEGIN
  BEGIN
    INSERT INTO public.p_dlyexp (exp_desc) VALUES ('Must collide');
    RAISE EXCEPTION 'Expected a duplicate primary key before repair';
  EXCEPTION WHEN unique_violation THEN
    NULL;
  END;
END;
$$;

\ir ../../drizzle/migrations/0004_repair_expense_identity_sequence.sql
\ir ../../drizzle/migrations/0005_ensure_expense_identity.sql

DO $$
DECLARE
  new_uid bigint;
BEGIN
  INSERT INTO public.p_dlyexp (exp_desc) VALUES ('First private expense') RETURNING uid INTO new_uid;
  IF new_uid <= 5000 THEN
    RAISE EXCEPTION 'New expense ID must exceed all imported IDs';
  END IF;
  IF (SELECT count(*) FROM public.p_dlyexp WHERE uid IN (1, 5000)) <> 2 THEN
    RAISE EXCEPTION 'Repair changed existing IDs';
  END IF;
END;
$$;

-- A repeated repair must preserve an already-ahead sequence.
SELECT setval(pg_get_serial_sequence('public.p_dlyexp', 'uid'), 10000, true);
\ir ../../drizzle/migrations/0004_repair_expense_identity_sequence.sql
\ir ../../drizzle/migrations/0005_ensure_expense_identity.sql
DO $$
DECLARE
  new_uid bigint;
BEGIN
  INSERT INTO public.p_dlyexp (exp_desc) VALUES ('After repeat repair') RETURNING uid INTO new_uid;
  IF new_uid <= 10000 THEN
    RAISE EXCEPTION 'Repair rewound the identity sequence';
  END IF;
END;
$$;

-- Empty ledgers must also remain usable.
TRUNCATE public.p_dlyexp RESTART IDENTITY;
\ir ../../drizzle/migrations/0004_repair_expense_identity_sequence.sql
\ir ../../drizzle/migrations/0005_ensure_expense_identity.sql
INSERT INTO public.p_dlyexp (exp_desc) VALUES ('First entry in empty ledger');
-- Match the observed live schema: bigint primary key, no default or identity.
DROP TABLE public.p_dlyexp;
CREATE TABLE public.p_dlyexp (uid bigint PRIMARY KEY, exp_desc text);
INSERT INTO public.p_dlyexp (uid, exp_desc) VALUES (1, 'Existing'), (1609, 'Highest existing');
\ir ../../drizzle/migrations/0004_repair_expense_identity_sequence.sql
\ir ../../drizzle/migrations/0005_ensure_expense_identity.sql
DO $$
DECLARE
  new_uid bigint;
BEGIN
  INSERT INTO public.p_dlyexp (exp_desc) VALUES ('First generated expense') RETURNING uid INTO new_uid;
  IF new_uid <> 1610 THEN
    RAISE EXCEPTION 'Expected 1610, got %', new_uid;
  END IF;
  IF (SELECT count(*) FROM public.p_dlyexp WHERE uid IN (1, 1609)) <> 2 THEN
    RAISE EXCEPTION 'Identity creation changed existing IDs';
  END IF;
  IF (SELECT identity_generation FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'p_dlyexp' AND column_name = 'uid') <> 'BY DEFAULT' THEN
    RAISE EXCEPTION 'Expected GENERATED BY DEFAULT identity';
  END IF;
END;
$$;
INSERT INTO public.p_dlyexp (uid, exp_desc) VALUES (2000, 'Explicit ID remains allowed');
\ir ../../drizzle/migrations/0005_ensure_expense_identity.sql
DO $$
DECLARE
  new_uid bigint;
BEGIN
  INSERT INTO public.p_dlyexp (exp_desc) VALUES ('After repeat repair') RETURNING uid INTO new_uid;
  IF new_uid <= 2000 THEN
    RAISE EXCEPTION 'Repeated repair did not account for explicit IDs';
  END IF;
END;
$$;
ROLLBACK;
