-- Repair both plain bigint IDs and existing identity/serial sequences.
-- The migration runner must execute this migration in a transaction.
LOCK TABLE public.p_dlyexp IN ACCESS EXCLUSIVE MODE;

DO $$
DECLARE
  identity_sequence regclass;
  highest_uid bigint;
  existing_default text;
BEGIN
  identity_sequence := pg_get_serial_sequence('public.p_dlyexp', 'uid')::regclass;
  IF identity_sequence IS NULL THEN
    SELECT column_default INTO existing_default
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'p_dlyexp' AND column_name = 'uid';
    IF existing_default IS NOT NULL THEN
      RAISE EXCEPTION 'p_dlyexp.uid has an unexpected default; inspect it before adding identity';
    END IF;

    ALTER TABLE public.p_dlyexp
      ALTER COLUMN uid ADD GENERATED BY DEFAULT AS IDENTITY;
    identity_sequence := pg_get_serial_sequence('public.p_dlyexp', 'uid')::regclass;
  END IF;

  SELECT max(uid) INTO highest_uid FROM public.p_dlyexp;
  PERFORM setval(
    identity_sequence,
    GREATEST(COALESCE(highest_uid, 1), nextval(identity_sequence)),
    true
  );
END;
$$;
